package com.example.quizapp

import android.content.Context
import android.content.Intent
import android.os.Bundle
import android.widget.Toast
import androidx.activity.result.contract.ActivityResultContracts
import androidx.appcompat.app.AppCompatActivity
import com.example.quizapp.databinding.ActivityLoginBinding
import com.google.android.gms.auth.api.signin.*
import com.google.android.gms.common.api.ApiException
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.auth.GoogleAuthProvider

class LoginActivity : AppCompatActivity() {
    private lateinit var b: ActivityLoginBinding

    companion object {
        // default_web_client_id is generated by the google-services plugin from google-services.json
        fun client(c: Context): GoogleSignInClient = GoogleSignIn.getClient(
            c,
            GoogleSignInOptions.Builder(GoogleSignInOptions.DEFAULT_SIGN_IN)
                .requestIdToken(c.getString(c.resources.getIdentifier("default_web_client_id", "string", c.packageName)))
                .requestEmail().build()
        )
    }

    private val launcher = registerForActivityResult(ActivityResultContracts.StartActivityForResult()) { res ->
        try {
            val acct = GoogleSignIn.getSignedInAccountFromIntent(res.data).getResult(ApiException::class.java)
            val cred = GoogleAuthProvider.getCredential(acct.idToken, null)
            FirebaseAuth.getInstance().signInWithCredential(cred).addOnCompleteListener {
                if (it.isSuccessful) goHome() else toast("Sign-in failed: ${it.exception?.message}")
                b.btnGoogle.isEnabled = true
            }
        } catch (e: ApiException) {
            b.btnGoogle.isEnabled = true
            toast("Google sign-in cancelled/failed (${e.statusCode})")
        }
    }

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        b = ActivityLoginBinding.inflate(layoutInflater)
        setContentView(b.root)
        // Don't crash if Firebase isn't configured (missing/wrong google-services.json)
        val auth = try { FirebaseAuth.getInstance() } catch (e: Exception) { null }
        if (auth == null) {
            b.btnGoogle.isEnabled = false
            b.tvError.text = "Firebase is not configured. Add the correct app/google-services.json " +
                "(package com.example.quizapp), then rebuild."
            return
        }
        if (auth.currentUser != null) { goHome(); return }
        b.btnGoogle.setOnClickListener {
            b.btnGoogle.isEnabled = false
            try {
                launcher.launch(client(this).signInIntent)
            } catch (e: Exception) {
                b.btnGoogle.isEnabled = true
                b.tvError.text = "Sign-in setup error: ${e.message}"
            }
        }
    }

    private fun goHome() { startActivity(Intent(this, HomeActivity::class.java)); finish() }
    private fun toast(m: String) = Toast.makeText(this, m, Toast.LENGTH_LONG).show()
}
